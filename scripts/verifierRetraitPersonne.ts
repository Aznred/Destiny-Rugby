import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
import { anonymiserPersonnesRetirees, personneRetiree, sourcePersonneRetiree } from '../src/lib/retraitsPersonnes.js';
import { joueursFfrDuClub } from '../src/lib/joueursFfr.js';
import { catalogueBaseCarriere } from '../src/lib/ligue/catalogueCarriere.js';
import { carteSeniorAutorisee } from '../src/lib/ligue/eligibiliteJoueurs.js';
import { choixImage } from '../src/lib/avatars.js';
import { classifierFfr } from '../serveur/ffr/classification.js';
import { exigerPublication } from '../serveur/ffr/validation.js';
import { migrerCartesJeunesse } from '../src/lib/ligue/migrationJeunesse.js';
import type { EtatCarriereEnLigne } from '../src/lib/ligue/typesCarriere.js';

for (const nom of ['Gauthier METAIS', 'Gauthier Métais', 'MÉTAIS Gauthier']) {
  assert.ok(personneRetiree(nom));
  assert.equal(choixImage(nom), null);
}
assert.equal(personneRetiree('Gauthier Martin'), false);
for (const id of ['reel:gauthier metais', 'ffr_191423', 191423]) assert.ok(sourcePersonneRetiree(id));
const effectif = joueursFfrDuClub('A S Tournefeuille');
assert.ok(effectif.length > 20);
assert.ok(effectif.every(j => !personneRetiree(j.nom) && j.ffrId !== 191423));
assert.equal(effectif.find(j => j.nom === 'Sasha NDAME NGONDI')?.indexSource, 12, 'Le retrait conserve les indices historiques');
const catalogue = catalogueBaseCarriere();
assert.ok(catalogue.every(c => !personneRetiree(c.nom) && !sourcePersonneRetiree(c.sourceId)));
const carte = { ...catalogue[0], id: 'ancienne-carte', nom: 'Gauthier METAIS', sourceId: 'ffr_191423', proprietaire: null, photo: '/photo-copie.webp' };
assert.equal(carteSeniorAutorisee(carte, 'mixed'), false);
assert.equal(carteSeniorAutorisee({ ...carte, sourceId: 'ajout-manuel' }, 'mixed'), false);
assert.equal(carteSeniorAutorisee({ ...carte, nom: 'Carte spéciale', sourceId: 'speciale:test', speciale: { base: 'ffr_191423' } } as typeof carte, 'mixed'), false);
const ancienne = { effectif: [carte], fil: ['Essai de Gauthier Métais'], score: [14, 7], autre: { nom: 'Gauthier Martin', photo: '/autre.webp' } };
const nettoyee = anonymiserPersonnesRetirees(ancienne);
assert.equal(nettoyee.effectif[0].nom, 'Joueur retiré');
assert.equal(nettoyee.effectif[0].photo, undefined);
assert.equal(nettoyee.effectif[0].id, carte.id);
assert.equal(nettoyee.effectif[0].sourceId, carte.sourceId);
assert.deepEqual(nettoyee.fil, ['Essai de Joueur retiré']);
assert.equal(nettoyee.score, ancienne.score);
assert.equal(nettoyee.autre, ancienne.autre);
assert.equal(ancienne.effectif[0].nom, 'Gauthier METAIS');
assert.equal(anonymiserPersonnesRetirees(nettoyee), nettoyee);
const etat = { id: 'test', cartes: [carte], clubs: [], transactions: [], ventes: [], echanges: [], rencontres: [], histoire: [] } as unknown as EtatCarriereEnLigne;
migrerCartesJeunesse(etat, 1);
assert.equal(etat.cartes[0].retiree, true);
assert.equal(etat.cartes[0].nom, 'Joueur retiré');
const possedee = { ...carte, nom: 'Gauthier METAIS', retiree: undefined, proprietaire: 'club-test' };
const possesseur = { id: 'club-test', ovas: 100, composition: { titulaires: [carte.id], remplacants: [], capitaineId: carte.id } };
const avecProprietaire = { id: 'test', cartes: [possedee], clubs: [possesseur], transactions: [], ventes: [], echanges: [], rencontres: [], histoire: [] } as unknown as EtatCarriereEnLigne;
migrerCartesJeunesse(avecProprietaire, 1);
assert.equal(avecProprietaire.cartes.length, 2);
assert.ok(avecProprietaire.cartes[1].note >= carte.note);
assert.equal(possesseur.composition.titulaires[0], avecProprietaire.cartes[1].id);
assert.equal(possesseur.composition.capitaineId, avecProprietaire.cartes[1].id);
migrerCartesJeunesse(avecProprietaire, 2);
assert.equal(avecProprietaire.cartes.length, 2, 'La compensation ne se répète pas');
assert.throws(() => exigerPublication(classifierFfr({ ffr_id: 191423, first_name: 'Gauthier', last_name: 'Metais', sex: 'M', category: 'Senior', club: 'A S Tournefeuille', competition: 'Fédérale 1', season: '2025-2026', position: 'Deuxième ligne', matches: 12 })));
assert.equal(existsSync('public/photos/ffr/as-tournefeuille/191423_gauthier_metais.webp'), false);
console.log('Retrait vérifié : effectif, catalogue, anciennes cartes, portraits, récits, publication et indices stables.');
